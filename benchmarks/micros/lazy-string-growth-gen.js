// Generator for a lazy-compilation benchmark. This file is not the benchmark;
// running it prints the benchmark to stdout.
//
//   hermes benchmarks/micros/lazy-string-growth-gen.js > /tmp/bench.js
//   hermes -lazy /tmp/bench.js
//
// It also runs under node, which takes the parameters as arguments:
//
//   node lazy-string-growth-gen.js [modules] [literalsPerModule] [shared]
//
// Under hermes, edit the constants below instead. The default of 24000 modules
// x 8 literals produces a ~24MB file that takes a couple of seconds to run.
//
// The shape is a Metro-style bundle: N module factories registered up front and
// then required in order, each exporting a handful of object literals. Every
// factory is compiled on its first call, so the benchmark reports how long each
// decile of modules took. A flat curve means compiling a function costs the
// same no matter how much has already been compiled; a rising one means the
// cost accumulates.
//
// Pass "shared" to reuse the same property names in every module instead of
// generating unique ones.
// Object literals are identical either way, so if only the unique-key run
// slows down, the cost is in the module string table and not
// in the literal buffers.
//
// That is where the quadratic in ConsecutiveStringStorage::appendStorage was.

var out =
  typeof print === 'undefined'
    ? function (s) {
        process.stdout.write(s + '\n');
      }
    : print;
var argv = typeof process === 'undefined' ? [] : process.argv.slice(2);

var MODULES = Number(argv[0] || 24000);
var LITERALS = Number(argv[1] || 8);
var SHARED = argv[2] === 'shared';
var DECILE = Math.ceil(MODULES / 10);

// Key names are unique per (module, literal) unless SHARED, in which case every
// module's j-th literal repeats the same four names.
function key(i, j, suffix) {
  var prefix = SHARED ? '' : 'm' + i.toString(36) + '_';
  return 'k' + prefix + j.toString(36) + suffix;
}

out('// Generated by benchmarks/micros/lazy-string-growth-gen.js');
out(
  '// ' +
    MODULES +
    ' modules x ' +
    LITERALS +
    ' object literals, ' +
    (SHARED ? 'shared' : 'unique') +
    ' keys.',
);
out('var factories = new Array(' + MODULES + ');');

for (var i = 0; i < MODULES; i++) {
  var body = '';
  for (var j = 0; j < LITERALS; j++) {
    body +=
      '  exports.shape' +
      j +
      ' = { ' +
      key(i, j, 'a') +
      ': ' +
      i +
      ', ' +
      key(i, j, 'b') +
      ": 'v" +
      i +
      "', " +
      key(i, j, 'c') +
      ': ' +
      (j % 2 === 0) +
      ', ' +
      key(i, j, 'd') +
      ': [' +
      i +
      ', ' +
      j +
      '] };\n';
  }
  out('factories[' + i + '] = function (exports) {\n' + body + '};');
}

out(`
// Call each factory once; the call is what triggers its lazy compilation.
var deciles = [];
var start = Date.now();
var mark = start;
for (var i = 0; i < ${MODULES}; i++) {
  factories[i]({});
  if ((i + 1) % ${DECILE} === 0) {
    var now = Date.now();
    deciles.push(now - mark);
    mark = now;
  }
}
var total = Date.now() - start;
var ratio = deciles[deciles.length - 1] / deciles[0];

// Slope over the back half. Some growth early in the run is expected and
// harmless (the heap and the identifier table are still growing), after which
// the curve should be flat. A cost that accumulates instead keeps climbing all
// the way to the end, which is what this catches.
function mean(a) { var s = 0; for (var i = 0; i < a.length; i++) s += a[i]; return s / a.length; }
var tail = mean(deciles.slice(5)) / mean(deciles.slice(3, 5));

print('modules      ' + ${MODULES} + ' x ' + ${LITERALS} + ' literals, ${SHARED ? 'shared' : 'unique'} keys');
print('total        ' + total + ' ms');
print('per decile   ' + deciles.join(' '));
print('last / first ' + ratio.toFixed(2));
print('back-half    ' + tail.toFixed(2));
var pass = ratio < 2.2 && tail < 1.2;
print(pass ? 'PASS - per-module cost stops growing' : 'FAIL - per-module cost still grows');
`);
